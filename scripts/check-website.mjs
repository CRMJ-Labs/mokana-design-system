import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {chromium} from '@playwright/test';

const server=spawn(process.execPath,['node_modules/vite/bin/vite.js','preview','--config','vite.website.config.ts','--port','3011'],{stdio:'pipe'});
let browser;
try{
  await new Promise((resolve,reject)=>{
    const timer=setTimeout(()=>reject(new Error('El servidor web no respondió.')),15000);
    server.stdout.on('data',chunk=>{if(chunk.toString().includes('3011')){clearTimeout(timer);resolve();}});
    server.once('exit',code=>{clearTimeout(timer);reject(new Error(`El servidor terminó: ${code}`));});
  });
  browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:3011/introduction');
  await page.getByRole('heading',{name:'Ideas que toman forma.',exact:false}).waitFor();
  const paths=await page.locator('aside a').evaluateAll(links=>links.map(link=>new URL(link.href).pathname));
  assert.ok(paths.length>80);
  for(const path of paths){
    const response=await page.request.get(`http://127.0.0.1:3011${path}`);
    assert.equal(response.status(),200,path);
    assert.match(await response.text(),/src="\/assets\//,path);
  }
  await page.evaluate(()=>{window.__navigationMarker='same-document';});
  const sidebar=page.locator('aside');
  await page.locator('aside').getByRole('link',{name:'Button',exact:true}).scrollIntoViewIfNeeded();
  const sidebarScroll=await sidebar.evaluate(node=>node.scrollTop);
  const navigationTheme=await page.locator('.mk-website').getAttribute('data-theme');
  await page.locator('aside').getByRole('link',{name:'Button',exact:true}).click();
  assert.equal(new URL(page.url()).pathname,'/components/button');
  await page.locator('#sizes').getByRole('button',{name:'Continuar',exact:true}).first().waitFor();
  assert.equal(await page.evaluate(()=>window.__navigationMarker),'same-document','La navegación no debe recargar el documento');
  assert.equal(await sidebar.evaluate(node=>node.scrollTop),sidebarScroll);
  assert.equal(await page.locator('.mk-website').getAttribute('data-theme'),navigationTheme);
  await page.goBack();
  await page.getByRole('heading',{name:'Ideas que toman forma.',exact:false}).waitFor();
  await page.goForward();
  await page.locator('#sizes').getByRole('button',{name:'Continuar',exact:true}).first().waitFor();
  assert.equal(await page.evaluate(()=>window.__navigationMarker),'same-document');
  await page.reload();
  await page.locator('#sizes').getByRole('button',{name:'Continuar',exact:true}).first().waitFor();
  const before=await page.locator('.mk-website').getAttribute('data-theme');
  await page.locator('.mk-docs-header').getByRole('radio',{name:before==='light'?'Oscuro':'Claro'}).check();
  const after=await page.locator('.mk-website').getAttribute('data-theme');
  assert.notEqual(before,after);
  await page.reload();
  assert.equal(await page.locator('.mk-website').getAttribute('data-theme'),after);
  await page.goto('http://127.0.0.1:3011/components/address-input');
  await page.locator('#default').getByLabel('Dirección',{exact:true}).fill('Calle 93');
  await page.getByRole('option',{name:/Calle 93/}).click();
  await page.locator('#default').getByRole('button',{name:'Ingresar la dirección manualmente'}).click();
  assert.equal(await page.locator('#default').getByLabel('Ciudad',{exact:true}).inputValue(),'Bogotá');
  await page.goto('http://127.0.0.1:3011/components/avatar');
  await page.getByRole('heading',{name:'Avatar',exact:true,level:1}).waitFor();
  const stacking=page.locator('#stacking');
  const stackLevel=await stacking.locator('.mk-avatar-group-member').first().evaluate(node=>node.style.zIndex);
  await stacking.getByRole('button').click();
  assert.notEqual(await stacking.locator('.mk-avatar-group-member').first().evaluate(node=>node.style.zIndex),stackLevel);
  await page.locator('#fixed-overlap input').fill('24');
  assert.equal(await page.locator('#fixed-overlap .mk-avatar-group').evaluate(node=>node.style.getPropertyValue('--avatar-overlap')),'24px');
  await page.locator('#group summary').click();
  assert.equal(await page.locator('#group details').getAttribute('open'),'');
  assert.ok(await page.locator('.mk-avatar-placeholder').count()===3);
  await page.goto('http://127.0.0.1:3011/components/book');
  await page.getByRole('heading',{name:'Book',level:1}).waitFor();
  assert.equal(await page.locator('.mk-nav-pending').count(),0);
  await page.goto('http://127.0.0.1:3011/does-not-exist');
  await page.getByRole('heading',{name:'Página no encontrada'}).waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.goto('http://127.0.0.1:3011/components/address-input');
  await page.getByRole('heading',{name:'Address Input',level:1}).waitFor();
  await page.locator('.mk-api-reference').waitFor();
  await page.evaluate(()=>window.scrollTo({top:1000,behavior:'instant'}));
  const scrolled=await page.evaluate(()=>window.scrollY);
  assert.ok(scrolled>400,'The mobile regression must open the menu on a scrolled page');
  const menuToggle=page.getByRole('button',{name:'Menú',exact:true});
  await menuToggle.click();
  const menuBounds=await page.locator('#website-navigation').boundingBox();
  assert.ok(menuBounds.y>=63&&menuBounds.y<=65,'Mobile menu starts under the sticky header');
  assert.ok(menuBounds.y+menuBounds.height<=845,'Mobile menu stays inside the viewport');
  await page.locator('#website-navigation').evaluate(node=>node.scrollTop=500);
  assert.equal(await page.evaluate(()=>window.scrollY),scrolled,'Menu scrolling preserves page position');
  await page.keyboard.press('Escape');
  assert.equal(await menuToggle.getAttribute('aria-expanded'),'false');
  assert.equal(await menuToggle.evaluate(node=>node===document.activeElement),true);
  await menuToggle.click();
  assert.equal(Math.round((await page.locator('#website-navigation').boundingBox()).y),64,'Reopening a scrolled menu keeps it visible');

  await page.locator('aside').getByRole('link',{name:'Button',exact:true}).click();
  await page.locator('#sizes').getByRole('button',{name:'Continuar',exact:true}).first().waitFor();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
  assert.deepEqual(errors,[]);
  console.log(`${paths.length} rutas web: navegación, recarga, tema persistente, Address Input, páginas pendientes, 404 y móvil correctos.`);
}finally{
  await browser?.close();
  server.kill();
}
