import fs from 'node:fs';
const t=JSON.parse(fs.readFileSync(new URL('../tokens.json',import.meta.url)));
let css='/* Generated by scripts/build-tokens.mjs from tokens.json. */\n.mk {\n';
for(const [k,v]of Object.entries(t.primitives))css+=`  --${k}: ${v};\n`;
for(const [k,v]of Object.entries(t.spacing))css+=`  --space-${k}: ${v}px;\n`;
for(const [k,v]of Object.entries(t.radius))css+=`  --radius-${k}: ${v}px;\n`;
for(const value of t.typography.scale)css+=`  --font-size-${value}: ${value}px;\n`;
for(const [name,size]of Object.entries(t.typography.roles)){
  if(!t.typography.scale.includes(size))throw new Error(`Unknown typography size ${size} for ${name}`);
  css+=`  --text-${name}: var(--font-size-${size});\n`;
}
for(const [name,value]of Object.entries(t.typography.weights))css+=`  --weight-${name}: ${value};\n`;
for(const [name,value]of Object.entries(t.typography.lineHeights))css+=`  --leading-${name}: ${value};\n`;
for(const [name,value]of Object.entries(t.shadows))css+=`  --shadow-${name}: ${value};\n`;
css+=`  --font-primary: ${t.typography.primary||t.typography.body}, sans-serif;\n  --font-secondary: ${t.typography.secondary||t.typography.display}, sans-serif;\n  --font-display: ${t.typography.display||t.typography.primary||t.typography.body}, sans-serif;\n  --font-heading: ${t.typography.heading||t.typography.primary||t.typography.body}, sans-serif;\n  --font-body: ${t.typography.body||t.typography.primary}, sans-serif;\n`;
for(const name of ['fast','normal','slow'])css+=`  --duration-${name}: ${t.motion[name]}ms;\n`;
css+=`  --ease: ${t.motion.ease};\n}\n`;
for(const [i,selector]of ['.mk, .mk[data-theme="light"]','.mk[data-theme="dark"]'].entries()){css+=selector+' {\n';for(const [k,v]of Object.entries(t.semantic))css+=`  --${k}: var(--${v[i]});\n`;css+='}\n';}
for(const [product,theme]of Object.entries(t.productThemes||{})){
  css+=`\n.mk[data-product="${product}"] {\n`;
  for(const [k,v]of Object.entries(theme.base||{}))css+=`  --${k}: ${v};\n`;
  css+='}\n';
  for(const mode of ['light','dark']){
    const selector=mode==='light'?`.mk[data-product="${product}"],\n.mk[data-product="${product}"][data-theme="light"]`:`.mk[data-product="${product}"][data-theme="dark"]`;
    css+=selector+' {\n';
    for(const [k,v]of Object.entries(theme[mode]||{}))css+=`  --${k}: ${v};\n`;
    css+='}\n';
  }
}
const resolve=(name,mode,seen=new Set())=>{
  if(t.primitives[name])return t.primitives[name];
  if(seen.has(name)||!t.semantic[name])throw new Error(`Invalid semantic reference: ${name}`);
  return resolve(t.semantic[name][mode],mode,new Set([...seen,name]));
};
const colors=Object.fromEntries(['light','dark'].map((mode,i)=>[mode,Object.fromEntries(Object.entries(t.semantic).map(([key,values])=>[key,resolve(values[i],i)]))]));
const outputs={'../src/tokens.css':css,'../src/palette-defaults.generated.ts':'/* Generated by scripts/build-tokens.mjs. */\nexport const defaultPaletteSeeds='+JSON.stringify(t.paletteDefaults,null,2)+' as const;\nexport const defaultPaletteColors='+JSON.stringify(colors,null,2)+' as const;\n'};
const check=process.argv.includes('--check');
for(const [name,content]of Object.entries(outputs)){
  const file=new URL(name,import.meta.url);
  if(check){if(!fs.existsSync(file)||fs.readFileSync(file,'utf8').replaceAll('\r\n','\n')!==content)throw new Error(`${name} is stale. Run npm run tokens.`);}
  else fs.writeFileSync(file,content);
}
console.log(check?'Generated tokens are current.':'Generated CSS tokens and palette defaults.');
