import assert from 'node:assert/strict';
import {expect} from '@playwright/test';

export async function testInvoiceStates(page){
  const table=page.getByRole('table',{name:'Detalle de los productos',exact:true});
  const show=page.getByRole('combobox',{name:'Mostrar',exact:true});
  const approve=page.getByRole('button',{name:'Aprobar factura',exact:true});
  await expect(page.getByRole('tab',{name:'Ítems (520)',exact:true})).toHaveAttribute('aria-selected','true');
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow','99.87');
  await expect(approve).toBeDisabled();
  assert.equal(await page.locator('[data-slot=app-shell]').count(),1);
  assert.equal(await page.locator('[data-slot=admin-table]').count(),1);
  assert.deepEqual((await table.getByRole('columnheader').allTextContents()).map(text=>text.replace(/\s+/g,' ').trim()),['Referencia','Descripción','Cantidad','Unidad','Precio unit.USD','Valor totalUSD','Acciones']);
  for(const [value,count]of [['all',520],['correct',517],['pending',2],['failed',1],['edited',1]])assert.match(await show.locator(`option[value="${value}"]`).textContent(),new RegExp(`\\(${count}\\)`));
  assert.ok(await table.getByRole('img',{name:'Correcto',exact:true}).count()>0);
  await expect(page.getByRole('button',{name:'Descripción de NZ-10051: Por revisar',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Valor total de NZ-10057: Regla fallida',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Precio unitario de NZ-10063: Editado',exact:true})).toBeVisible();
  for(const theme of ['light','dark']){
    await page.getByRole('radio',{name:theme==='light'?'Claro':'Oscuro',exact:true}).check();
    await page.screenshot({path:`verification/invoice-review-desktop-${theme}.png`,animations:'disabled'});
  }
  await page.getByRole('radio',{name:'Claro',exact:true}).check();
  const search=page.getByRole('searchbox',{name:'Buscar ítems',exact:true});
  await search.fill('no existe');await expect(page.getByText('No hay coincidencias. Prueba otra referencia o descripción.',{exact:true})).toBeVisible();
  await search.fill('');await show.selectOption('pending');
  await expect(page.getByRole('button',{name:'NZ-10051',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'NZ-10060',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Descripción de NZ-10051: Por revisar',exact:true}).click();
  const description=page.getByRole('dialog',{name:'Descripción · Por revisar',exact:true});
  await expect(description).toContainText('confianza media');
  await description.getByRole('button',{name:'Confirmar dato',exact:true}).click();
  await expect(description).not.toBeVisible();
  await expect(show.locator('option[value=pending]')).toContainText('(1)');
  await page.getByRole('button',{name:'Cantidad de NZ-10060: Por revisar',exact:true}).click();
  await page.getByRole('dialog',{name:'Cantidad · Por revisar',exact:true}).getByRole('button',{name:'Confirmar dato',exact:true}).click();
  await expect(page.getByText('Todos los datos pendientes fueron revisados.',{exact:true})).toBeVisible();
  await show.selectOption('failed');
  await page.getByRole('button',{name:'Valor total de NZ-10057: Regla fallida',exact:true}).click();
  const failed=page.getByRole('dialog',{name:'Valor total · Regla fallida',exact:true});
  await expect(failed).toContainText('48,00 USD');await expect(failed).toContainText('60,00 USD');
  await page.screenshot({path:'verification/invoice-review-rule-detail.png',animations:'disabled'});
  await failed.getByRole('button',{name:'Usar total calculado (48,00)',exact:true}).click();
  await expect(page.getByText('No hay ítems con reglas fallidas.',{exact:true})).toBeVisible();
  await expect(show.locator('option[value=failed]')).toContainText('(0)');
  await show.selectOption('edited');
  await page.getByRole('button',{name:'Precio unitario de NZ-10063: Editado',exact:true}).click();
  const edited=page.getByRole('dialog',{name:'Precio unitario · Editado',exact:true});
  await expect(edited).toContainText('Antes');await expect(edited).toContainText('1,30');await expect(edited).toContainText('0,99');
  await page.keyboard.press('Escape');await expect(edited).not.toBeVisible();
  await expect(approve).toBeDisabled();
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow','99.97');
  await page.getByRole('button',{name:'Revisar siguiente',exact:true}).click();
  const field=page.getByRole('dialog',{name:'NIT / tax ID del proveedor',exact:true});
  await field.getByRole('button',{name:'Guardar dato',exact:true}).click();await expect(field.getByRole('alert')).toContainText('Escribe el dato');
  await field.getByRole('textbox',{name:'NIT / tax ID del proveedor',exact:true}).fill('91330200DEMO001');
  await field.getByRole('button',{name:'Guardar dato',exact:true}).click();
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow','100');await expect(approve).toBeEnabled();
  await page.getByRole('tab',{name:'Ítems (520)',exact:true}).click();
  await show.selectOption('all');await search.fill('NZ-10024');
  await page.getByRole('button',{name:'NZ-10024',exact:true}).click();
  await expect(page.locator('.ir-source-link')).toContainText('NZ-10024');
  const sourceText=await page.locator('.ir-paper tr[data-highlighted=true]').textContent();
  await page.getByRole('button',{name:'Acciones de NZ-10024',exact:true}).click();await page.getByRole('menuitem',{name:'Editar ítem',exact:true}).click();
  const editor=page.getByRole('dialog',{name:'Editar NZ-10024',exact:true});
  await expect(editor.getByRole('textbox',{name:'Referencia',exact:true})).toHaveValue('NZ-10024');
  await editor.getByRole('spinbutton',{name:'Cantidad',exact:true}).fill('2500');await editor.getByRole('combobox',{name:'Unidad',exact:true}).selectOption('KG');
  await editor.getByRole('button',{name:'Guardar cambios',exact:true}).click();
  await expect(approve).toBeDisabled();
  await expect(page.getByRole('button',{name:'Cantidad de NZ-10024: Editado',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Unidad de NZ-10024: Editado',exact:true})).toBeVisible();
  const totalError=page.getByRole('button',{name:'Valor total de NZ-10024: Regla fallida',exact:true});await expect(totalError).toBeVisible();
  assert.equal(await page.locator('.ir-paper tr[data-highlighted=true]').textContent(),sourceText,'Editing extracted values must not alter the original document.');
  await totalError.click();await page.getByRole('dialog',{name:'Valor total · Regla fallida',exact:true}).getByRole('button',{name:'Editar dato',exact:true}).click();
  await editor.getByRole('button',{name:'Recalcular total',exact:true}).click();
  await expect(editor.getByRole('spinbutton',{name:'Valor total (USD)',exact:true})).toHaveValue('4750');
  await editor.getByRole('button',{name:'Guardar cambios',exact:true}).click();
  await expect(approve).toBeEnabled();await expect(show.locator('option[value=failed]')).toContainText('(0)');
  await expect(page.getByRole('button',{name:'Valor total de NZ-10024: Editado',exact:true})).toBeVisible();
  await page.getByRole('tab',{name:'Reglas',exact:true}).click();await expect(page.getByRole('heading',{name:'Los datos son consistentes',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Historial',exact:true}).click();
  const history=page.getByRole('dialog',{name:'Historial de revisión',exact:true});await expect(history).toContainText('Dato confirmado');await expect(history).toContainText('Regla resuelta');await expect(history).toContainText('Ítem actualizado');
  await page.keyboard.press('Escape');await expect(history).not.toBeVisible();
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Exportar',exact:true}).click();assert.equal((await download).suggestedFilename(),'NB-2611-0520-items.csv');
  await approve.click();await page.getByRole('dialog',{name:'Aprobar esta factura',exact:true}).getByRole('button',{name:'Confirmar aprobación',exact:true}).click();
  await expect(page.getByRole('button',{name:'Factura aprobada',exact:true})).toBeDisabled();
  await page.getByRole('tab',{name:'Ítems (520)',exact:true}).click();await expect(page.getByRole('button',{name:'Acciones de NZ-10024',exact:true})).toBeDisabled();
}
